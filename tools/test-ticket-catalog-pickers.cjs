const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const repairPicker = read('src/workorders/WorkOrderRepairPickerWindow.tsx');
const productPicker = read('src/components/ProductsWindow.tsx');
const workOrderItems = read('src/workorders/ItemsTable.tsx');
const saleItems = read('src/sales/SaleItemsTable.tsx');
const workOrderWindow = read('src/workorders/NewWorkOrderWindow.tsx');
const workOrderItemDialog = read('src/workorders/WorkOrderItemDialog.tsx');
const checkoutWindow = read('src/workorders/CheckoutWindow.tsx');
const saleWindow = read('src/sales/SaleWindow.tsx');
const workOrderSidebar = read('src/workorders/WorkOrderSidebar.tsx');
const saleItemDialog = read('src/sales/SaleItemDialog.tsx');

assert.doesNotMatch(repairPicker, /RepairItemForm/, 'Work-order selection must not expose the Admin repair editor.');
assert.match(repairPicker, /Repair selection/, 'Work-order picker must present a compact selection summary.');
assert.match(repairPicker, /Pick catalog repair/, 'Work-order picker must use the approved popup heading and layout.');
assert.match(repairPicker, /Parent part family|Exact inventory part|No inventory part linked/, 'Repair selection must clearly identify its inventory relationship.');
assert.match(productPicker, /Inventory selection/, 'Sale picker must present a compact inventory summary.');
assert.match(productPicker, /Catalog details are managed in Admin → Inventory/, 'Sale picker must separate catalog administration from ticket selection.');
assert.match(workOrderItems, /Catalog-linked details/, 'Work-order line editing must distinguish catalog data from ticket-only fields.');
assert.match(saleItems, /Inventory-linked item/, 'Sale line editing must distinguish inventory data from ticket-only fields.');
assert.match(workOrderItems, /gb-ticket-item-dialog/, 'Work-order custom item editing must open in a dialog rather than expand below the item list.');
assert.match(saleItems, /gb-ticket-item-dialog/, 'Sale custom item editing must open in a dialog rather than expand below the item list.');
assert.match(workOrderItemDialog, /Part source/, 'Work-order custom item dialog must use the approved part-source chooser.');
assert.match(workOrderItemDialog, /Order from supplier/, 'Work-order custom item dialog must provide the approved supplier-order flow.');
assert.match(workOrderItemDialog, /Salvaged spare part/, 'Work-order custom item dialog must support salvaged spare parts.');
assert.match(saleItemDialog, /Add custom sale item/, 'Sales custom items must use the same approved centered popup design.');
assert.match(saleItemDialog, /Purchased locally/, 'Sales custom items must record a local purchase when applicable.');
assert.match(saleItemDialog, /Order from supplier/, 'Sales custom items must record ordered product delivery details.');
assert.match(saleWindow, /Delivery overview/, 'Sales should show ordered-product information as an at-a-glance overview.');
assert.doesNotMatch(saleWindow, /Part ordered URL/, 'Sales must not expose unrelated work-order part URL fields.');
assert.match(workOrderSidebar, /Ticket summary/, 'Work-order and sale sidebars must show an automatic ticket summary.');
assert.doesNotMatch(workOrderSidebar, /type="datetime-local"/, 'The shared sidebar must not collect manual order, completion, or checkout dates.');
assert.match(saleWindow, /initialSaleCheckoutForm/, 'The first successful sale checkout must automatically print the sales form.');
assert.match(saleWindow, /SaleTechnicianField/, 'Sales must show technician assignment at the top of the form.');
assert.doesNotMatch(workOrderWindow, /<h4 className="text-sm font-semibold text-zinc-200">Parts tracking<\/h4>/, 'Work-order-wide parts tracking must not duplicate tracking recorded on individual ordered items.');
assert.match(workOrderWindow, /Complete required work-order details/, 'Save and checkout must use a blocking required-details dialog.');
assert.match(workOrderWindow, /initialCheckoutReleaseForm/, 'The first qualifying work-order payment must automatically print the release form.');
assert.match(checkoutWindow, /useState<boolean>\(false\);\s*\/\/ Receipt starts unchecked/, 'Checkout must leave receipt printing unchecked by default.');

console.log('Ticket catalog picker layout checks passed.');
